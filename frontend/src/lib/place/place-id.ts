/**
 * `placeId` 가 백엔드가 받아들일 수 있는 모양인가 — 이슈 #496.
 *
 * **상세 컨트롤러가 `@PathVariable long` 이라 숫자가 아니면 무조건 400 이다**
 * (`docs/screen-inventory.md` §3 — `PLACE_113`). 물어보기 전에 답이 정해져 있는 요청이라
 * 보내지 않는다. `/places/abc` 하나에 상세·적합도·산책 안전 **세 요청이 나가 400 이 3건**
 * 났고, 적합도·산책 안전은 **반려견 조건까지 쿼리에 실어** 보냈다 — 실패가 확정된 요청에
 * 개인 조건이 실려 나가는 모양이다. 콘솔 오류 3건이 진짜 오류를 덮기도 한다.
 *
 * **Snowflake 라 `Number()` 로 바꿔 보지 않는다.** id 는 19자리까지 가고
 * `Number.MAX_SAFE_INTEGER` 는 16자리라, 숫자로 바꾸는 순간 정밀도를 잃는다 — 서버가
 * `Long` 으로 읽으므로 화면도 **문자열 그대로** 다룬다 (공통명세 S1 과 같은 이유).
 * 그래서 판정도 문자열 패턴으로 한다.
 *
 * **받아들이는 것은 숫자만이다.** 부호(`-1`)·공백·`+`·소수점·지수 표기는 전부 400 이다.
 * 앞자리 0(`007`)은 `Long.parseLong` 이 받아들이므로 막지 않는다 — 여기서 거르면 서버가
 * 답할 수 있는 주소를 화면이 먼저 거절하는 것이 된다.
 *
 * 길이 상한은 두지 않는다. 20자리 이상은 서버가 400 으로 답하는데, 그 경계는 서버의
 * `Long` 범위라 화면이 베껴 두면 둘이 갈릴 수 있다 — **모양만 보고 범위는 서버에 맡긴다.**
 */
const PLACE_ID_PATTERN = /^\d+$/

export function isPlaceId(value: string): boolean {
  return PLACE_ID_PATTERN.test(value)
}
