/**
 * 요청 메모에 보이는 권역 → 지역 칩 제안 — 이슈 #1381.
 *
 * dev 에서 "서귀포 위주로 이동은 짧게" 라고 적었더니 결과 세 곳이 모두 제주시 · 조천이었다
 * (`ux-review-2026-10-11.md` §3-3). 메모는 자유 문장이라 서버가 지역 조건으로 읽지 않는다. 폼에는
 * 이미 `지역` 칩(`sigunguCode`)이 있는데 접기 안에 있어 메모와 연결되지 않았다.
 *
 * **제안만 한다 — 자동으로 바꾸지 않는다.** "서귀포 말고" 같은 부정을 문장에서 가를 수 없다.
 *
 * - `'제주'` · `'제주도'` 만으로는 좁히지 않는다 — 섬 전체를 부르는 말이다. `'제주시'` 는 좁힌다.
 * - 두 권역의 낱말이 함께 나오면 제안하지 않는다 — 어느 쪽인지 단정할 수 없다.
 * - 낱말은 시 이름과 널리 쓰이는 읍면 · 동네 이름이다. 목록에 없는 곳은 제안이 없을 뿐 틀리지 않는다.
 */
const REGION_WORDS: Record<'3' | '4', readonly string[]> = {
  // 서귀포시
  '3': ['서귀포', '중문', '성산', '표선', '남원', '안덕', '대정', '모슬포', '위미'],
  // 제주시
  '4': [
    '제주시',
    '애월',
    '한림',
    '한경',
    '협재',
    '조천',
    '함덕',
    '구좌',
    '월정',
    '세화',
    '우도',
    '추자',
  ],
}

/** 제안할 `sigunguCode`. 없으면 `null` */
export function regionHintFromNote(note: string): '3' | '4' | null {
  const hits = (Object.keys(REGION_WORDS) as ('3' | '4')[]).filter((code) =>
    REGION_WORDS[code].some((word) => note.includes(word)),
  )

  return hits.length === 1 ? (hits[0] ?? null) : null
}
