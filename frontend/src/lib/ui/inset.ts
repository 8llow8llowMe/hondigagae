/**
 * 좌우 여백 축 — DESIGN.md §7-1 (모바일 16 · 데스크톱 40 · 레일 오른쪽 24).
 *
 * **왼쪽 인셋은 페이지 전체가 하나로 쓰고, 오른쪽만 자리마다 갈린다** (#386).
 * 왼쪽 세로선은 헤더 바 · 레일 · 본문이 전부 공유하는 **페이지의 기준선**이라 하나여야
 * 하고, 오른쪽은 옆에 무엇이 서 있느냐에 따른 **국소 간격**이라 갈려도 눈에 걸리지 않는다.
 * 레일의 오른쪽은 열 구분선까지의 간격이고 비교 대상이 없다.
 *
 * 그래서 `rail` 은 `main` 에 **오른쪽 축소(`lg:pr-6`)만 얹은 값**이다. 예전에는 `lg:px-6`
 * 으로 양쪽을 24 로 내렸는데, 그러면 1024 이상에서 헤더 로고(40)와 레일 첫 글자(24)가
 * **같은 컨테이너 경계에서 16px 갈라진다** (#376 이 1440 컨테이너를 도입해 두 요소가 같은
 * 경계를 공유하게 되면서 드러났다. 1920 실측: 컨테이너 240 · 로고 280 · 레일 264).
 *
 * **왼쪽을 40 으로 올리는 값은 레일 안쪽 폭 16px 이다** (32 가 아니다 — 오른쪽은 24 로
 * 남기므로). 1024 실측: 골든타임 시각 줄 347 → 331, 곡선 323 → 307. **둘 다 원래
 * 가로 스크롤러라 넘침이 새로 생기지 않고 보이는 시각 칸도 그대로다**(14~19시).
 * 반대 방향(헤더를 24 로 내린다)은 레일이 없는 화면 — 마이페이지 · 반려견 · 저장한 곳 ·
 * 일정 목록 · AI 일정 생성 — 전부에서 같은 어긋남을 새로 만든다. 레일 화면보다 많다.
 *
 * **`md` 가 아니라 `lg` 에서 갈리는 것이 두 번째 규칙이다.**
 * 2단 레이아웃은 1024(`lg`)부터고, 그 아래에서는 레일이 레일이 아니라 **한 컬럼의 한
 * 블록**이다. 그때는 본문과 같은 세로선에 서야 한다 — 옆에 아무 열도 없는데 혼자
 * 24 로 들어가 있으면, 한 줄로 쌓인 블록들의 글자 왼쪽 끝이 지그재그가 된다.
 *
 * 실측(885px 한 컬럼, 고치기 전): 날짜 24 · 프로필 24 · **판정 40** · 골든타임 24 ·
 * **병원 40** · 권역 40 — 세로 기준선이 다섯 번 꺾였다.
 *
 * **문자열을 컴포넌트마다 적지 않는다.** `Banner` 하나만 이 전환을 구현하고 나머지가
 * `md:px-6` 에서 멈춰 있던 것이 위 실측의 원인이다. 규칙이 한 군데 있으면 한 군데만 어긋난다.
 * 헤더 바 안쪽과 장소 상세의 두 판정 패널도 같은 문자열을 따로 적어 두고 있었다 — #386 에서
 * `INSET_CLASS` 참조로 바꿨다.
 *
 * 세로 여백은 여기서 정하지 않는다 — 블록마다 다르고, 그 차이에는 각자 이유가 있다.
 *
 * **`panel` 은 고정 폭 컨테이너 전용이다.** 긴급 시설 지도 화면의 데스크톱 패널(400px)과
 * 모바일 시트가 그렇다 — `md:`/`lg:` 는 항상 **뷰포트** 기준이라, `main`/`rail` 을 그
 * 안에 쓰면 1024 이상에서 40px 이 컨테이너 자신의 폭이 아니라 화면 폭을 보고 붙는다.
 * 400px 패널 안 내용이 320px 로 줄어 실제 행(평평한 `px-4`,
 * `emergency-map-panel.tsx`)과 다른 세로선에 선다. `panel` 은 그 트랩을 피하려고 끝까지
 * 평평하다 — 컨테이너 자체가 이미 고정 폭이라 더 넓은 여백을 줄 뷰포트가 없다.
 */
export type Inset = 'main' | 'rail' | 'panel'

export const INSET_CLASS: Record<Inset, string> = {
  main: 'px-4 md:px-10',
  rail: 'px-4 md:px-10 lg:pr-6',
  panel: 'px-4',
}

/**
 * 레일 블록이 좌우로 흘러넘쳐야 할 때 (가로 스크롤 줄 등). 인셋을 음수 margin 으로
 * 상쇄하고 같은 값을 padding 으로 되돌려, 스크롤 내용이 여백 밖까지 이어지되 첫·마지막
 * 항목은 여백 안에 선다.
 */
export const INSET_BLEED_CLASS: Record<Inset, string> = {
  main: '-mx-4 px-4 md:-mx-10 md:px-10',
  rail: '-mx-4 px-4 md:-mx-10 md:px-10 lg:-mr-6 lg:pr-6',
  panel: '-mx-4 px-4',
}

/**
 * 오른쪽으로만 흘러넘치는 변형. 왼쪽에 스크롤되지 않는 것(행 라벨 열 등)이 붙어 있어
 * **그쪽으로 넘칠 자리가 없을 때** 쓴다 — 골든타임 곡선이 그렇다.
 *
 * 양쪽 변형을 그대로 쓰면 스크롤 내용이 라벨 열 아래로 파고든다.
 */
