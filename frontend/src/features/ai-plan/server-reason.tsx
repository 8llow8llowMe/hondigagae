import type { ReactNode } from 'react'

/**
 * 서버가 내려준 실패 사유 (#710).
 *
 * **말투가 갈리는 것을 배치로 푼다.** DESIGN.md §1 은 FE 문구를 해요체로 고정하면서
 * **서버 문구를 예외로** 둔다 — FE 가 서버 문구를 다시 쓰지 않기 때문이고(styling-guide
 * §7), 그 판단 자체는 옳다. 문제는 예외를 **제목 바로 아래 본문 자리**에 놓은 것이었다:
 *
 * ```text
 * 일정을 만들지 못했어요            ← FE, 해요체
 * AI 일정 생성이 제한 시간을 넘겼습니다.  ← 서버, 합쇼체
 * ```
 *
 * 둘이 같은 급의 문단으로 나란히 서면 **한 화면이 두 사람의 말투로 말한다** — §1 이
 * 정확히 금지하는 그림이고, 예외 규칙은 그것을 허용하려던 것이 아니다.
 *
 * 왼쪽 선 하나로 **인용의 자리**를 만들면 같은 문장이 "이 화면이 하는 말" 이 아니라
 * "서버가 말한 사유" 로 읽힌다. 문구는 한 글자도 고치지 않으므로 예외 규칙도 그대로다.
 *
 * **테두리는 왼쪽 하나뿐이라 radius 를 주지 않는다** — 한쪽 선에 둥근 모서리를 주면
 * 선이 허공에서 꺾인다.
 *
 * **세로 padding 도 주지 않는다.** 선이 글줄과 정확히 같은 높이여야 인용으로 읽히고,
 * 스케일 밖 값(`py-0.5`)을 쓰면 DESIGN.md §4 의 스페이싱 스케일에 구멍이 난다 —
 * `token-usage.test.ts` 가 그 첫 구멍을 잡는다.
 *
 * 성공·안내 문구에는 쓰지 않는다. 이 장치의 뜻은 "받아 적은 말" 이고, 그 구분이 필요한
 * 곳은 원인을 서버만 아는 실패 경로다.
 */
export function ServerReason({ children }: { children: ReactNode }) {
  return (
    <p className="border-border-strong text-body-2 text-fg-muted border-l-2 pl-3">{children}</p>
  )
}
