package com.hondigagae.domainlayer.insight.domain.enums;

import com.hondigagae.common.dto.metadata.CodeNameDescribable;
import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 제주 날씨 권역.
 *
 * <p><b>한라산이 섬을 기후로 갈라 놓는다는 것이 이 기능의 전제다.</b> 제주는 가로 70km 남짓인데
 * 해발 1,950m 산이 한가운데 있어, 같은 시각에 북부는 비가 오고 남부는 개어 있는 일이 흔하다.
 * "제주 날씨"를 한 값으로 말하면 그 차이가 통째로 사라진다.
 *
 * <p>다섯으로 나눈 근거는 두 가지다.
 *
 * <ul>
 *   <li><b>행정 경계</b> — 제주시/서귀포시. 중기예보의 기온 지점이 실제로 이 둘로 갈리고,
 *       실측에서 같은 회차에 최고기온이 32도/31도로 달랐다 ({@link MidTermRegion})</li>
 *   <li><b>기상 격자</b> — 동부·서부·산간은 행정구역이 아니라 기상청 5km 격자가 다르다.
 *       대표 좌표가 서로 다른 격자에 떨어지는 것을 확인하고 골랐다</li>
 * </ul>
 *
 * <h2>대표 좌표를 쓰는 이유</h2>
 *
 * 권역마다 격자를 하나만 정해 <b>기존 격자 캐시를 그대로 재사용한다.</b> 권역 안을 여러 격자로
 * 훑으면 정확해지는 대신 호출이 권역 수의 몇 배로 늘어난다. 개발계정 한도가 일 1,000건이라
 * 그 거래는 맞지 않는다 - 권역 비교가 답하려는 질문은 "어디가 더 나은가"이지 "몇 도인가"가 아니다.
 *
 * <p>대표 좌표는 그 권역에서 <b>사람이 실제로 가는 곳</b>으로 잡았다. 권역 도형의 무게중심을
 * 쓰면 아무도 가지 않는 바다나 중산간이 대표가 된다.
 */
@Getter
@RequiredArgsConstructor
public enum JejuRegion implements CodeNameDescribable {

    /** 제주시 시내. 격자 (53, 38). */
    NORTH("제주시권", "제주공항과 시내를 포함한 북부입니다. 한라산 북쪽이라 겨울 북서풍의 영향을 먼저 받습니다.",
        33.4996d, 126.5312d),

    /** 서귀포 시내. 격자 (53, 33). 한라산 남쪽이라 북부보다 따뜻하다. */
    SOUTH("서귀포권", "서귀포 시내와 중문을 포함한 남부입니다. 한라산이 북풍을 막아 겨울에도 북부보다 따뜻합니다.",
        33.2541d, 126.5600d),

    /** 성산 일대. 격자 (60, 37). 섬에서 바람이 가장 센 축이다. */
    EAST("동부권", "성산과 우도 방면입니다. 탁 트인 해안이라 바람이 강하게 부는 날이 많습니다.",
        33.4586d, 126.9420d),

    /** 한림·협재 일대. 격자 (47, 36). */
    WEST("서부권", "한림과 협재 방면입니다. 해안 산책로가 많아 노면 온도와 바람을 함께 봐야 합니다.",
        33.3940d, 126.2400d),

    /**
     * 1100고지 일대. 격자 (52, 35).
     *
     * <p><b>해발이 달라 기온이 해안과 크게 벌어진다.</b> 이 권역을 따로 두지 않으면 산간의
     * 추위가 해안 평균에 묻혀 "괜찮다"로 나온다.
     */
    HALLA("한라산권", "1100고지 등 산간입니다. 해발이 높아 해안보다 기온이 낮고 날씨가 빨리 바뀝니다.",
        33.3617d, 126.4930d);

    private final String displayName;
    private final String description;
    /** 권역 대표 좌표. 격자 캐시 키가 여기서 나온다. */
    private final double lat;
    private final double lng;

    /**
     * 중기예보 구역. 권역 비교는 오늘~내일만 다루므로 지금은 쓰지 않지만, 권역과 예보구역의
     * 대응을 한곳에 적어 둔다 - 나중에 기간을 늘릴 때 이 매핑을 다시 추측하지 않게 한다.
     */
    public MidTermRegion midTermRegion() {
        return this == SOUTH ? MidTermRegion.SEOGWIPO_SI : MidTermRegion.JEJU_SI;
    }
}
